    #[test]
    fn utf16_round_trips_scalar_boundaries_and_clamps() {
        let text = "a😀é中";
        for (utf8, utf16) in [(0, 0), (1, 1), (5, 3), (7, 4), (10, 5)] {
            assert_eq!(utf16_to_utf8(text, utf16), utf8);
            assert_eq!(utf8_to_utf16(text, utf8), utf16);
        }
        assert_eq!(utf16_to_utf8(text, 2), 5);
        assert_eq!(utf16_to_utf8(text, usize::MAX), text.len());
        assert_eq!(utf8_to_utf16(text, usize::MAX), 5);
        assert_eq!(utf16_to_utf8("", 42), 0);
    }

    #[test]
    fn navigation_keeps_combining_and_zwj_graphemes_whole() {
        let text = "a\u{301}👩‍💻🇩🇪z";
        let mut offset = 0;
        for grapheme in text.graphemes(true) {
            let next = next_boundary(text, offset);
            assert_eq!(&text[offset..next], grapheme);
            assert_eq!(previous_boundary(text, next), offset);
            offset = next;
        }
        assert_eq!(previous_boundary(text, 0), 0);
        assert_eq!(next_boundary(text, text.len()), text.len());
    }

